"""Original offline numpy synthesis and device-safe pygame audio for ECHO.

No samples, external instruments, network requests or third-party compositions
are used. All WAVs are deterministic 22050Hz, signed 16-bit stereo PCM.
"""
from __future__ import annotations

import math
import time
import wave
from pathlib import Path

import numpy as np
import pygame

from .art import ASSET_ROOT, SEED

AUDIO_ROOT = ASSET_ROOT / "audio"
AUDIO_VERSION = 3
SAMPLE_RATE = 22050
LOOP_SECONDS = 32.0
EFFECT_SECONDS = {"jump": .38, "land": .34, "death": 1.8, "gate": 1.5,
                  "grab": .30, "checkpoint": 2.4, "gravity": 1.15,
                  "win": 5.0, "footstep": .20, "tick": .10,
                  "magnet": .32, "magnet_capture": .55, "magnet_release": .40}


def _noise(rng, count, cutoff=900, highpass=25, slope=1.0):
    """Periodic band-limited noise, generated by a deterministic spectral filter."""
    source = rng.standard_normal(count).astype(np.float32)
    spectrum = np.fft.rfft(source)
    frequencies = np.fft.rfftfreq(count, 1 / SAMPLE_RATE)
    weight = 1 / np.sqrt(1 + (frequencies / cutoff) ** (2 * slope))
    weight *= frequencies / np.sqrt(frequencies * frequencies + highpass * highpass)
    weight[0] = 0
    result = np.fft.irfft(spectrum * weight, n=count)
    rms = np.sqrt(np.mean(result * result))
    return (result / max(rms, 1e-9)).astype(np.float32)


def _pan(signal, position=0.0):
    position = max(-1.0, min(1.0, position))
    angle = (position + 1) * math.pi / 4
    return np.column_stack((signal * math.cos(angle), signal * math.sin(angle)))


def _bell(t, frequency, decay=1.4):
    # Slightly inharmonic resonators resemble a small weathered glass/metal bell.
    result = np.zeros_like(t)
    for ratio, gain, damping in ((1, 1, 1), (2.013, .29, 1.5),
                                  (2.731, .12, 2.1), (4.107, .055, 3.2)):
        result += gain * np.sin(math.tau * frequency * ratio * t) * np.exp(-t * damping / decay)
    return result * (1 - np.exp(-t * 120))


def _reverb(signal, delays=(.113, .271, .433), gains=(.22, .13, .08), loop=False):
    result = signal.copy()
    for delay, gain in zip(delays, gains):
        offset = round(delay * SAMPLE_RATE)
        if loop:
            result += np.roll(signal, offset, axis=0) * gain
        elif offset < len(signal):
            result[offset:] += signal[:-offset] * gain
    return result


def _place_loop(track, signal, start, pan, gain):
    stereo = _pan(signal, pan) * gain
    offset = round(start * SAMPLE_RATE) % len(track)
    end = min(len(track), offset + len(stereo))
    track[offset:end] += stereo[:end - offset]
    remainder = len(stereo) - (end - offset)
    if remainder:
        track[:remainder] += stereo[-remainder:]


def _ambience():
    count = round(LOOP_SECONDS * SAMPLE_RATE)
    t = np.arange(count, dtype=np.float64) / SAMPLE_RATE
    rng = np.random.default_rng(SEED + 401)
    track = np.zeros((count, 2), dtype=np.float64)
    for channel in range(2):
        wind = _noise(rng, count, 680, 38, 1.9)
        breathe = .65 + .18 * np.sin(math.tau * t / 32 + channel * 1.4)
        breathe += .09 * np.sin(math.tau * t / 8 + channel * .9)
        track[:, channel] += wind * breathe * .022
        # All frequencies/LFOs complete integer cycles over the loop duration.
        for freq, amplitude, phase in ((55, .022, .7), (82.5, .012, 1.8),
                                       (110, .006, .2), (164.75, .0035, 2.6)):
            wavering = .19 * np.sin(math.tau * t / 16 + phase)
            mode = np.sin(math.tau * freq * t + wavering + channel * .19)
            track[:, channel] += mode * amplitude * (.83 + .17 * np.cos(math.tau * t / 32 + phase))
    # Intermittent distant drainage droplets / pressure knocks.
    drop_t = np.arange(round(.8 * SAMPLE_RATE)) / SAMPLE_RATE
    for n, start in enumerate((1.3, 5.8, 10.1, 17.6, 22.3, 29.1)):
        knock = (np.sin(math.tau * (116 + n * 7) * drop_t) * np.exp(-drop_t * 22)
                 + .20 * _noise(rng, len(drop_t), 1500) * np.exp(-drop_t * 42))
        knock *= 1 - np.exp(-drop_t * 240)
        _place_loop(track, knock, start, (-1) ** n * .72, .035)
    track = _reverb(track, loop=True)
    return track


def _music():
    count = round(LOOP_SECONDS * SAMPLE_RATE)
    t = np.arange(count, dtype=np.float64) / SAMPLE_RATE
    track = np.zeros((count, 2), dtype=np.float64)
    # A custom nine-event phrase. The bell register is intentionally spacious,
    # with asymmetrical rests rather than a familiar song or rhythmic quotation.
    phrase = ((1.0, 293.665, -.38, .095), (4.5, 440.000, .30, .064),
              (8.25, 349.228, -.19, .070), (11.0, 329.628, .48, .044),
              (16.25, 220.000, -.40, .074), (20.5, 293.665, .16, .068),
              (24.0, 523.251, .42, .044), (27.5, 440.000, -.32, .047),
              (30.0, 349.228, .10, .035))
    bell_t = np.arange(round(5.5 * SAMPLE_RATE)) / SAMPLE_RATE
    for start, frequency, pan, gain in phrase:
        bell = _bell(bell_t, frequency, 1.65)
        # Fade the very end before wrapping the tail into the start of the loop.
        bell[-2048:] *= np.linspace(1, 0, 2048)
        _place_loop(track, bell, start, pan, gain)
    # Low bowed sine modes: shallow phase modulation, no abrupt chord changes.
    for n, freq in enumerate((73.4375, 110.0, 146.84375)):
        mode = np.sin(math.tau * freq * t + .13 * np.sin(math.tau * t / 32 + n))
        envelope = .62 + .38 * np.sin(math.tau * t / 32 + n * 1.8) ** 2
        track += _pan(mode * envelope * (.014 / (n + 1)), (n - 1) * .28)
    return _reverb(track, (.183, .417, .731, 1.173), (.29, .19, .115, .065), loop=True)


def _effect(name):
    count = round(EFFECT_SECONDS[name] * SAMPLE_RATE)
    t = np.arange(count, dtype=np.float64) / SAMPLE_RATE
    rng = np.random.default_rng(SEED + 1000 + list(EFFECT_SECONDS).index(name) * 37)
    signal = np.zeros(count, dtype=np.float64)
    if name == "jump":
        frequency = 155 + 440 * (1 - np.exp(-t * 8))
        phase = math.tau * np.cumsum(frequency) / SAMPLE_RATE
        signal = np.sin(phase) * np.exp(-t * 12) * .13
        signal += _noise(rng, count, 1500, 170, 2) * np.exp(-t * 20) * .033
    elif name in ("land", "footstep"):
        decay = 28 if name == "land" else 42
        gain = .15 if name == "land" else .074
        phase = math.tau * (64 * t + 46 * (1 - np.exp(-t * 20)) / 20)
        signal = np.sin(phase) * np.exp(-t * decay) * gain
        signal += _noise(rng, count, 2100, 60, 2) * np.exp(-t * (decay + 7)) * gain * .44
        signal += _noise(rng, count, 670, 160) * np.exp(-((t - .05) / .03) ** 2) * gain * .12
    elif name == "death":
        phase = math.tau * (87 * t + 39 * (1 - np.exp(-t * 2)) / 2)
        signal = (np.sin(phase) + .3 * np.sin(phase * 1.49)) * np.exp(-t * 2.9) * .12
        signal += _noise(rng, count, 1200, 32, 2) * np.exp(-t * 7) * .045
        signal = _reverb(signal)
    elif name == "gate":
        noise = _noise(rng, count, 1350, 55, 1.6)
        motor = .046 * np.sin(math.tau * 73 * t) + .019 * np.sin(math.tau * 146 * t)
        rubbing = (.60 + .4 * np.sin(math.tau * t * 13.1) ** 2)
        envelope = np.sin(math.pi * np.minimum(1, t / 1.5)) ** .75
        signal = (noise * .036 * rubbing + motor) * envelope
        for start in (.07, 1.15):
            relative = np.maximum(0, t - start)
            signal += .10 * np.sin(math.tau * 127 * relative) * np.exp(-relative * 32) * (t >= start)
        signal = _reverb(signal, (.091, .263), (.20, .10))
    elif name == "grab":
        signal = _noise(rng, count, 1750, 100) * np.exp(-t * 36) * .046
        signal += np.sin(math.tau * 176 * t) * np.exp(-t * 32) * .065
        signal += _bell(t, 586, .065) * .035
    elif name == "checkpoint":
        for start, frequency, gain in ((0, 293.665, .15), (.32, 440, .10), (.83, 587.33, .065)):
            relative = np.maximum(0, t - start)
            signal += _bell(relative, frequency, .72) * gain * (t >= start)
        signal = _reverb(signal, (.183, .419), (.20, .13))
    elif name == "gravity":
        phase = math.tau * (470 * t - 340 * t * t / (2 * 1.15))
        signal = (np.sin(phase) + .22 * np.sin(phase * 1.5)) * .065
        signal *= np.sin(math.pi * t / 1.15) ** 1.5
        signal += _noise(rng, count, 1000, 170, 2) * np.sin(math.pi * t / 1.15) * .016
        signal = _reverb(signal, (.093, .219), (.21, .10))
    elif name == "win":
        for start, frequency, gain in ((0, 293.665, .12), (.5, 440, .09),
                                       (1.13, 523.251, .074), (1.95, 587.33, .06)):
            relative = np.maximum(0, t - start)
            signal += _bell(relative, frequency, 1.28) * gain * (t >= start)
        signal += np.sin(math.tau * 146.83 * t) * .023 * np.sin(math.pi * t / 5) ** 2
        signal = _reverb(signal, (.271, .547, .813), (.24, .16, .08))
    elif name == "tick":
        signal = np.sin(math.tau * 1130 * t) * np.exp(-t * 42) * .075
        signal += np.sin(math.tau * 1695 * t) * np.exp(-t * 56) * .018
    elif name == "magnet":
        signal = _noise(rng, count, 1850, 260) * np.exp(-t * 65) * .042
        signal += np.sin(math.tau * 92 * t) * np.sin(math.pi * t / .32) ** 2 * .08
    elif name == "magnet_capture":
        # A short iron clack and rising overtone make physical contact audible.
        signal = _noise(rng, count, 2600, 120) * np.exp(-t * 60) * .09
        signal += _bell(t, 392, .10) * .13 + _bell(t, 784, .15) * .06
    elif name == "magnet_release":
        phase = math.tau * (290 * t - 190 * t * t / .8)
        signal = np.sin(phase) * np.exp(-t * 12) * .12
        signal += _noise(rng, count, 850, 150) * np.exp(-t * 30) * .027
    # Every effect has a short click-free attack and a zeroed tail.
    attack = max(1, round(.004 * SAMPLE_RATE))
    tail = min(count // 2, round(.035 * SAMPLE_RATE))
    signal[:attack] *= np.linspace(0, 1, attack)
    signal[-tail:] *= np.linspace(1, 0, tail)
    stereo = _pan(signal, 0)
    # A restrained decorrelated reflection gives small effects room, not loudness.
    delay = min(count - 1, round(.012 * SAMPLE_RATE))
    stereo[delay:, 1] += signal[:-delay] * .075
    stereo[-tail:] *= np.linspace(1, 0, tail)[:, None]
    return stereo


def _write_wave(path, samples):
    # Fixed synthesis gains preserve intended dynamics; safety limiting is only
    # invoked for unexpectedly excessive peaks, never aggressive normalization.
    samples = np.nan_to_num(samples)
    peak = float(np.max(np.abs(samples)))
    if peak > .70:
        samples *= .70 / peak
    pcm = np.rint(np.clip(samples, -.70, .70) * 32767).astype("<i2")
    with wave.open(str(path), "wb") as output:
        output.setnchannels(2)
        output.setsampwidth(2)
        output.setframerate(SAMPLE_RATE)
        output.writeframes(pcm.tobytes())


def audio_asset_names():
    return ["ambience.wav", "music.wav"] + [f"{name}.wav" for name in EFFECT_SECONDS]


def ensure_audio_assets(force=False, root: Path | None = None):
    """Create only ECHO-owned synthesized WAVs; safe without a mixer/device."""
    root = Path(root) if root is not None else AUDIO_ROOT
    root.mkdir(parents=True, exist_ok=True)
    for name, generate in (("ambience", _ambience), ("music", _music)):
        path = root / f"{name}.wav"
        if force or not path.is_file():
            _write_wave(path, generate())
    for name in EFFECT_SECONDS:
        path = root / f"{name}.wav"
        if force or not path.is_file():
            _write_wave(path, _effect(name))
    return [root / name for name in audio_asset_names()]


class Audio:
    """Two quiet looping beds and named effects, with safe no-device fallback.

    ``update`` emits speed-dependent footsteps only. Explicit jump/land/etc.
    events remain the game's responsibility, preventing duplicate landing cues.
    ``close`` stops this object's sounds but does not shut down a shared mixer.
    """

    def __init__(self, enabled=True):
        self.enabled = bool(enabled)
        self.muted = not self.enabled
        self.available = False
        self.error = None
        self._sounds = {}
        self._loops = []
        self._step_timer = 0.0
        self._last_played = {}
        self._priority_channel = 2
        if not self.enabled:
            return
        self._start()

    def _start(self):
        """Lazily open the device, including unmuting a disabled startup."""
        try:
            if pygame.mixer.get_init() is None:
                pygame.mixer.init(frequency=SAMPLE_RATE, size=-16, channels=2, buffer=512)
            ensure_audio_assets()
            # Do not reduce an already configured mixer channel count.
            pygame.mixer.set_num_channels(max(12, pygame.mixer.get_num_channels()))
            pygame.mixer.set_reserved(2)
            self._sounds = {name[:-4]: pygame.mixer.Sound(str(AUDIO_ROOT / name))
                            for name in audio_asset_names()}
            self._sounds["ambience"].set_volume(.72)
            self._sounds["music"].set_volume(.50)
            for name in EFFECT_SECONDS:
                self._sounds[name].set_volume(.65 if name == "footstep" else .85)
            self._loops = [pygame.mixer.Channel(0), pygame.mixer.Channel(1)]
            self._loops[0].play(self._sounds["ambience"], loops=-1, fade_ms=1400)
            self._loops[1].play(self._sounds["music"], loops=-1, fade_ms=1800)
            self.available = True
        except (pygame.error, OSError, ValueError) as exc:
            # A laptop without an audio sink must still be able to play the game.
            self.error = str(exc)
            for channel in self._loops:
                channel.stop()
            self._loops = []
            self._sounds = {}
            self.available = False

    @staticmethod
    def ensure_assets(force=False):
        return ensure_audio_assets(force=force)

    def play(self, name):
        if not self.available or self.muted or not self.enabled:
            return
        name = {"step": "footstep", "landing": "land", "pickup": "grab",
                "respawn": "checkpoint", "finish": "win"}.get(name, name)
        if name not in EFFECT_SECONDS:
            return
        now = time.monotonic()
        cooldown = {"gate": .7, "grab": .12, "death": .5, "checkpoint": .6,
                    "win": 1.0, "gravity": .25}.get(name, .065)
        if now - self._last_played.get(name, -math.inf) < cooldown:
            return
        try:
            channel = next((pygame.mixer.Channel(index)
                            for index in range(2, pygame.mixer.get_num_channels())
                            if not pygame.mixer.Channel(index).get_busy()), None)
            if channel is None and name in ("death", "win", "checkpoint"):
                # Never steal the ambience/music channels, even at FX saturation.
                channel = pygame.mixer.Channel(self._priority_channel)
                self._priority_channel = 2 + (self._priority_channel - 1) % (pygame.mixer.get_num_channels() - 2)
            if channel is not None:
                channel.play(self._sounds[name])
                self._last_played[name] = now
        except pygame.error:
            self.available = False

    def update(self, speed: float, grounded: bool, dt: float):
        if not self.available or self.muted or not self.enabled:
            self._step_timer = 0.0
            return
        if not grounded or abs(speed) < 22:
            self._step_timer = 0.0
            return
        # One call per frame, and never catch up a long pause with many footsteps.
        self._step_timer += max(0.0, min(.10, float(dt)))
        interval = max(.24, min(.48, 48 / max(1, abs(speed))))
        if self._step_timer >= interval:
            self._step_timer %= interval
            self.play("footstep")

    def set_muted(self, muted: bool):
        self.muted = bool(muted)
        if not self.muted and not self.enabled:
            self.enabled = True
            self._start()
        if not self.available:
            return
        try:
            for channel in self._loops:
                channel.pause() if self.muted else channel.unpause()
            if self.muted:
                for name in EFFECT_SECONDS:
                    self._sounds[name].stop()
        except pygame.error:
            self.available = False

    def close(self):
        try:
            if pygame.mixer.get_init() is not None:
                for sound in self._sounds.values():
                    sound.stop()
        except pygame.error:
            pass
        self.available = False
        self._loops = []
        self._sounds = {}
